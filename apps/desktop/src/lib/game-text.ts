import { t } from './app-language';
const patterns: [RegExp, string][] = [
  [/^(?:Чему равно|What is) (\d+) × (\d+)\?$/, 'Чему равно {p0} × {p1}?'],
  [/^Игрок (\d+) отправляется в тюрьму$/, 'Игрок {p0} отправляется в тюрьму'],
  [/^Игрок (\d+) → игроку (\d+): аренда (\d+)$/, 'Игрок {p0} → игроку {p1}: аренда {p2}'],
  [/^Игрок (\d+) объявил банкротство$/, 'Игрок {p0} объявил банкротство'],
  [/^Игрок (\d+) сдался$/, 'Игрок {p0} сдался'],
  [
    /^Игрок (\d+): проданы все постройки цветовой группы$/,
    'Игрок {p0}: проданы все постройки цветовой группы',
  ],
  [/^Игрок (\d+): (.+) → (.+)$/, 'Игрок {p0}: {p1} → {p2}'],
  [/^Игрок (\d+): (.+) · (.+)$/, 'Игрок {p0}: {p1} · {p2}'],
  [/^Игрок (\d+): (.+)$/, 'Игрок {p0}: {p1}'],
  [/^Обслуживание станций: −(\d+)$/, 'Обслуживание станций: −{p0}'],
  [/^Сбор (\d+)$/, 'Сбор {p0}'],
  [/^Аукцион: (\d+)$/, 'Аукцион: {p0}'],
];
const actions: Record<string, string> = {
  buy: 'Купить',
  mortgage: 'Заложить',
  redeem: 'Выкупить залог',
  build: 'Построить дом',
  sell: 'Продать постройку',
  end: 'Завершить ход',
  bankrupt: 'Банкротство',
};
export function localizeGameText(text: string) {
  for (const [pattern, key] of patterns) {
    const match = pattern.exec(text);
    if (match)
      return t(
        key,
        Object.fromEntries(
          match.slice(1).map((value, index) => [`p${index}`, t(actions[value] ?? value)]),
        ),
      );
  }
  return t(text);
}
