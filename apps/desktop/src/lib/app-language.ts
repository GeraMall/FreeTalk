const languageKey = 'trlka.ui-language';

export const appLanguages = {
  ru: 'Русский',
  en: 'English',
  'zh-CN': '简体中文',
  kk: 'Қазақша',
  be: 'Беларуская',
  ka: 'ქართული',
  es: 'Español',
} as const;

export type AppLanguage = keyof typeof appLanguages;

export function isAppLanguage(value: string | null): value is AppLanguage {
  return value !== null && Object.hasOwn(appLanguages, value);
}

export function appLanguage(): AppLanguage {
  try {
    const value = localStorage.getItem(languageKey);
    return isAppLanguage(value) ? value : 'ru';
  } catch {
    return 'ru';
  }
}

export async function changeAppLanguage(language: AppLanguage) {
  const previous = localStorage.getItem(languageKey);
  localStorage.setItem(languageKey, language);
  try {
    if (isTauri()) {
      const { relaunch } = await import('@tauri-apps/plugin-process');
      await relaunch();
    } else {
      window.location.reload();
    }
  } catch (error) {
    if (previous === null) localStorage.removeItem(languageKey);
    else localStorage.setItem(languageKey, previous);
    throw error;
  }
}

export function formatChatCallLabel(kind: string | null | undefined, text: string) {
  if (kind !== 'call' || appLanguage() === 'ru') return text;
  const started = /^(.*) начал(?:а)? (?:(голосовой|групповой) )?звонок$/u.exec(text);
  return started
    ? t(started[2] === 'групповой' ? '{name} начал групповой звонок' : '{name} начал звонок', {
        name: started[1],
      })
    : t(text);
}

