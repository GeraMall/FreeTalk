const additionalTranslations: Record<
  Exclude<AppLanguage, 'ru' | 'en' | 'zh-CN'>,
  Record<string, string>
> = {
  kk: kazakh,
  be: belarusian,
  ka: georgian,
  es: spanish,
};

export function t(text: string, values?: Record<string, unknown>) {
  const language = appLanguage();
  let translated = text;
  if (language === 'en' || language === 'zh-CN') {
    translated = translations[text]?.[language === 'en' ? 0 : 1] ?? text;
  } else if (language !== 'ru') {
    const catalog = additionalTranslations[language];
    if (Object.hasOwn(catalog, text)) translated = catalog[text];
  }
  if (language !== 'ru') {
    const entry = (reviewTranslations as Record<string, Partial<Record<AppLanguage, string>>>)[
      text
    ];
    const gameEntry = (gameTranslations as Record<string, Partial<Record<AppLanguage, string>>>)[
      text
    ];
    translated =
      (interactionTranslations as Record<string, Partial<Record<AppLanguage, string>>>)[text]?.[
        language
      ] ??
      gameEntry?.[language] ??
      entry?.[language] ??
      translated;
  }
  return values
    ? translated.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token))
    : translated;
}
